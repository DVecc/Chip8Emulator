{
    VkDebugUtilsMessengerCreateInfoEXT debugInfo = getDebugMessengerCreateInfo();

    if (CreateDebugUtilsMessengerEXT(instance, &debugInfo, nullptr, &debugMessenger) != VK_SUCCESS) 
    {
       LOG_FATAL(L"failed to set up debug messenger!");
    }
}

