void VK_Renderer::createChip8Texture() {
    // Create image
    createImage(64, 32, VK_FORMAT_R8_UNORM, VK_IMAGE_TILING_OPTIMAL,
                VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT,
                VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT,
                chip8TextureImage, chip8TextureImageMemory);

    // Create image view
    chip8TextureImageView = createImageView(chip8TextureImage, VK_FORMAT_R8_UNORM);

    // Create sampler
    VkSamplerCreateInfo samplerInfo{};
    samplerInfo.sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO;
    samplerInfo.magFilter = VK_FILTER_NEAREST;
    samplerInfo.minFilter = VK_FILTER_NEAREST;
    samplerInfo.addressModeU = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    samplerInfo.addressModeV = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    samplerInfo.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    samplerInfo.anisotropyEnable = VK_FALSE;
    samplerInfo.borderColor = VK_BORDER_COLOR_INT_OPAQUE_BLACK;
    samplerInfo.unnormalizedCoordinates = VK_FALSE;
    samplerInfo.compareEnable = VK_FALSE;
    samplerInfo.mipmapMode = VK_SAMPLER_MIPMAP_MODE_NEAREST;

    VK_CHECK(vkCreateSampler(device, &samplerInfo, nullptr, &chip8TextureSampler));
}

void VK_Renderer::updateChip8Texture(uint8_t* chip8Buffer) {
    VkDeviceSize imageSize = static_cast<VkDeviceSize>(64) * 32;

    VkBuffer stagingBuffer;
    VkDeviceMemory stagingBufferMemory;

    createBuffer(imageSize, VK_BUFFER_USAGE_TRANSFER_SRC_BIT,
                 VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT,
                 stagingBuffer, stagingBufferMemory);

    // Copy CHIP-8 buffer into staging buffer (convert 0/1 to 0/255)
    void* data;
    vkMapMemory(device, stagingBufferMemory, 0, imageSize, 0, &data);
    uint8_t* dst = static_cast<uint8_t*>(data);
    for (int i = 0; i < imageSize; ++i) {
        dst[i] = chip8Buffer[i] ? 255 : 0;
    }
    vkUnmapMemory(device, stagingBufferMemory);

    // Transition image layout and copy
    transitionImageLayout(chip8TextureImage, VK_FORMAT_R8_UNORM,
                          VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);

    copyBufferToImage(stagingBuffer, chip8TextureImage, 64, 32);

    transitionImageLayout(chip8TextureImage, VK_FORMAT_R8_UNORM,
                          VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);

    vkDestroyBuffer(device, stagingBuffer, nullptr);
    vkFreeMemory(device, stagingBufferMemory, nullptr);
}

